import fs from "node:fs";
const questions = JSON.parse(
  fs.readFileSync(
    new URL("../src/data/questions.json", import.meta.url),
    "utf8",
  ),
);
const bank = Object.fromEntries(
  questions.map((q) => [
    q.id,
    { revision: q.revision, correctIndex: q.correctIndex },
  ]),
);
const content = `// Generated by npm run quiz:receiver. Copy alongside Code.gs.\nconst HMI_QUIZ_BANK_VERSION = ${Math.max(...questions.map((q) => q.revision))};\nconst HMI_QUIZ_BANK = Object.freeze(${JSON.stringify(bank, null, 2)});\n`;
const destination = new URL(
  "../integrations/google-apps-script/QuestionBank.gs",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if (
    !fs.existsSync(destination) ||
    fs.readFileSync(destination, "utf8") !== content
  )
    throw new Error(
      "Receiver bank is stale. Run npm run quiz:receiver and update the Apps Script deployment.",
    );
} else fs.writeFileSync(destination, content);
console.log(
  `${process.argv.includes("--check") ? "Checked" : "Generated"} receiver metadata for ${questions.length} questions.`,
);
